package main

import (
	"context"
	"database/sql"
	"fmt"
	"time"

	_ "github.com/jackc/pgx/v5/stdlib"
)

// openDB connects to PostgreSQL (dsn is a postgres:// URL or a key=value DSN)
// and creates the tables if they do not exist yet.
//
// The connection is retried for up to 60 seconds, since the database (or the
// network path to it) may not be ready right after the container starts.
func openDB(dsn string) (*sql.DB, error) {
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		return nil, err
	}
	deadline := time.Now().Add(60 * time.Second)
	for {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		err = db.PingContext(ctx)
		cancel()
		if err == nil {
			break
		}
		if time.Now().After(deadline) {
			db.Close()
			return nil, fmt.Errorf("connect: %w", err)
		}
		time.Sleep(2 * time.Second)
	}
	if err := createTables(db); err != nil {
		db.Close()
		return nil, err
	}
	return db, nil
}

// Dates are stored as ISO 8601 UTC strings ("2026-01-20T15:00:00.000Z"), which
// is also what the API returns. They use the "C" collation so that comparison
// and ORDER BY are plain byte order regardless of the database's locale.
func createTables(db *sql.DB) error {
	_, err := db.Exec(`
CREATE TABLE IF NOT EXISTS metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    qty DOUBLE PRECISION NOT NULL,
    units TEXT NOT NULL,
    date TEXT COLLATE "C" NOT NULL,
    source TEXT COLLATE "C" NOT NULL DEFAULT '',
    metadata TEXT,
    UNIQUE(name, date, source)
);

CREATE TABLE IF NOT EXISTS blood_pressure (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    systolic DOUBLE PRECISION NOT NULL,
    diastolic DOUBLE PRECISION NOT NULL,
    units TEXT NOT NULL,
    date TEXT COLLATE "C" NOT NULL,
    source TEXT COLLATE "C" NOT NULL DEFAULT '',
    metadata TEXT,
    UNIQUE(date, source)
);

CREATE TABLE IF NOT EXISTS heart_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min DOUBLE PRECISION NOT NULL,
    avg DOUBLE PRECISION NOT NULL,
    max DOUBLE PRECISION NOT NULL,
    units TEXT NOT NULL,
    date TEXT COLLATE "C" NOT NULL,
    source TEXT COLLATE "C" NOT NULL DEFAULT '',
    metadata TEXT,
    UNIQUE(date, source)
);

CREATE TABLE IF NOT EXISTS sleep_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TEXT COLLATE "C" NOT NULL,
    in_bed_start TEXT NOT NULL DEFAULT '',
    in_bed_end TEXT NOT NULL DEFAULT '',
    sleep_start TEXT NOT NULL DEFAULT '',
    sleep_end TEXT NOT NULL DEFAULT '',
    core DOUBLE PRECISION NOT NULL DEFAULT 0,
    rem DOUBLE PRECISION NOT NULL DEFAULT 0,
    deep DOUBLE PRECISION NOT NULL DEFAULT 0,
    awake DOUBLE PRECISION NOT NULL DEFAULT 0,
    in_bed DOUBLE PRECISION NOT NULL DEFAULT 0,
    asleep DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_sleep DOUBLE PRECISION NOT NULL DEFAULT 0,
    units TEXT NOT NULL,
    source TEXT COLLATE "C" NOT NULL DEFAULT '',
    metadata TEXT,
    UNIQUE(date, source)
);

CREATE TABLE IF NOT EXISTS workouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    start TEXT COLLATE "C" NOT NULL,
    "end" TEXT COLLATE "C" NOT NULL,
    duration DOUBLE PRECISION NOT NULL,
    active_energy_burned_qty DOUBLE PRECISION,
    active_energy_burned_units TEXT,
    distance_qty DOUBLE PRECISION,
    distance_units TEXT,
    heart_rate_data TEXT,
    heart_rate_recovery TEXT,
    step_count TEXT,
    temperature_qty DOUBLE PRECISION,
    humidity_qty DOUBLE PRECISION,
    intensity_qty DOUBLE PRECISION,
    created_at TEXT DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS workout_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id TEXT NOT NULL UNIQUE,
    locations TEXT NOT NULL,
    created_at TEXT DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS workouts_start_idx ON workouts (start);
`)
	return err
}
